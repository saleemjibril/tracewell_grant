export function getDefaultTagForTab(tabId) {
  return TAB_TAGS[tabId]?.[0]?.id ?? null;
}

export function grantMatchesTabTag(grant, tabId, tagId) {
  if (!tagId) return true;

  switch (tabId) {
    case "popular-funders":
      return grant.funder === tagId;
    case "region":
      return grant.regions.includes(tagId);
    case "sector":
      return grant.sectors.includes(tagId);
    case "funding-size":
      return grant.fundingSize === tagId;
    case "deadline":
      return grant.deadlineType === tagId;
    case "accredited-partner":
      return grant.accreditedPartner === tagId;
    default:
      return true;
  }
}
